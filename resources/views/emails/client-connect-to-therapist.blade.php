<br/><br/>
The main difference between psychotherapy and coaching is focus. Psychotherapy focuses on mental
health issues and facilitating insight into your past. Although coaching can help you see how your past
contributes to your pr
esent, it’s not its main focus. Coaching is focused on your goals for the future.
Coaching facilitates your present strengths and resources to get you where you want to be.
<br/><br/>
Coaching does not provide diagnoses or treatment of mental disorders as defined by
the American
Psychiatric Association. It should be noted that Pineapple Support therapists do not provide mental
disorder diagnoses either.
<br/><br/>
Please discuss any questions about the distinction between coaching and psychotherapy directly with
your coach
during your first session and they will be happy to explain further.
